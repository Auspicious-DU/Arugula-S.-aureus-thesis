make_DT_dir <- function(path) {
  
  dir.create(
    path,
    recursive = TRUE,
    showWarnings = FALSE
  )
  
}


read_required_csv_DT <- function(
    file_path,
    object_name
) {
  
  if (!file.exists(file_path)) {
    
    stop(
      "Required file not found for ",
      object_name,
      ":\n",
      file_path
    )
    
  }
  
  readr::read_csv(
    file_path,
    show_col_types = FALSE
  )
}


